export function organizationInstant(local: string, timeZone: string) {
  const target = Date.parse(`${local}:00Z`);
  if (!Number.isFinite(target)) throw new Error("INVALID_LOCAL_TIME");
  const wall = (ms: number) => {
    const parts = new Intl.DateTimeFormat("en-CA", {
      timeZone,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      hourCycle: "h23",
    }).formatToParts(new Date(ms));
    const p = (k: string) => parts.find((x) => x.type === k)!.value;
    return `${p("year")}-${p("month")}-${p("day")}T${p("hour")}:${p("minute")}`;
  };
  let candidate = target;
  for (let i = 0; i < 3; i++)
    candidate += target - Date.parse(`${wall(candidate)}:00Z`);
  if (
    wall(candidate) !== local ||
    wall(candidate - 3600000) === local ||
    wall(candidate + 3600000) === local
  )
    throw new Error("INVALID_LOCAL_TIME");
  return new Date(candidate).toISOString();
}
