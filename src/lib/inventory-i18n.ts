export function moneyText(minor: string) {
  const negative = minor.startsWith("-");
  const raw = minor.replace(/^-/, "").padStart(3, "0");
  return `${negative ? "−" : ""}${raw.slice(0, -2).replace(/\B(?=(\d{3})+(?!\d))/g, " ")},${raw.slice(-2)}`;
}
export const quantityText = (s: string) =>
  s.replace(/(\.\d*?)0+$/, "$1").replace(/\.$/, "");
